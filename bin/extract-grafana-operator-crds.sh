#!/usr/bin/env bash
# Deflate the Grafana Operator CRDs into the materialize-monitoring-crds chart.
#
# Upstream publishes no standalone grafana-operator-crds chart: the CRDs ship
# inside the grafana-operator chart itself, either as templates (mutable) or as
# a crds/ directory (immutable, install-only). Neither can be disabled, so the
# main chart pins `grafana-operator.crds.immutable=true` -- which keeps them out
# of the release manifest -- and we vendor them here as a local subchart so the
# CRDs chart owns their lifecycle, the same way prometheus-operator-crds does.
#
# The CRDs are lifted out of the grafana-operator tarball vendored under the
# main chart, so they always match the operator version we deploy.
#
# Re-run this whenever the vendored grafana-operator chart version changes.
# Output is checked in.

PROG=$0
# set cwd to repo root
cd "$(dirname "$0")/../" || exit 1
# shellcheck source=tools/shlib/common.sh
source "tools/shlib/common.sh"
set -o errexit -o errtrace -o nounset -o pipefail
_register_traceback

# Where the vendored operator tarball lives and where the deflated chart goes.
OPERATOR_CHART_DIR="charts/materialize-monitoring/charts"
OUT_CHART_DIR="charts/materialize-monitoring-crds/charts/grafana-operator-crds"

function _require_progs() {
    local missing=false
    for prog in "$@"; do
        if ! _has_prog "$prog"; then
            _error "required program not found on PATH: $prog"
            missing=true
        fi
    done
    [ "$missing" = false ] || exit 1
}

function _find_tarball() {
    # Resolve the single vendored grafana-operator-*.tgz tarball.
    local matches=("$OPERATOR_CHART_DIR"/grafana-operator-*.tgz)
    if [ ! -e "${matches[0]}" ]; then
        _error "no grafana-operator-*.tgz under $OPERATOR_CHART_DIR"
        _error "run: helm dependency update charts/materialize-monitoring"
        exit 1
    fi
    if [ "${#matches[@]}" -gt 1 ]; then
        _error "multiple grafana-operator tarballs found; expected exactly one:"
        printf '  %s\n' "${matches[@]}" >&2
        exit 1
    fi
    echo "${matches[0]}"
}

_require_progs yq tar

TARBALL=$(_find_tarball)
CHART_VERSION=$(basename "$TARBALL" .tgz | sed 's/^grafana-operator-//')
APP_VERSION=$(tar xzfO "$TARBALL" grafana-operator/Chart.yaml | yq e '.appVersion')
_info "Deflating CRDs from $TARBALL (chart $CHART_VERSION, operator $APP_VERSION)"

WORK_DIR=$(mktemp -d)
trap 'rm -rf "$WORK_DIR"' EXIT

# `files/crds/` is the mutable (templated) copy upstream renders from; the
# immutable `charts/crds/crds/` copy holds the same documents. Either works,
# but files/crds/ is the one upstream regenerates from the operator repo.
tar xzf "$TARBALL" -C "$WORK_DIR" grafana-operator/files/crds
CRD_SRC_DIR="$WORK_DIR/grafana-operator/files/crds"

# Wipe previously generated templates so CRDs dropped upstream do not linger.
rm -rf "${OUT_CHART_DIR:?}/templates"
mkdir -p "$OUT_CHART_DIR/templates"

plurals=()
for src in "$CRD_SRC_DIR"/*.yaml; do
    # grafana.integreatly.org_grafanadashboards.yaml -> grafanadashboards
    plural=${src##*_}
    plural=${plural%.yaml}
    plurals+=("$plural")
    out_file="$OUT_CHART_DIR/templates/crd-${plural}.yaml"

    _info "  $plural -> $out_file"

    {
        echo "{{- if .Values.crds.${plural}.enabled -}}"
        echo "{{/* GENERATED BY $PROG -- DO NOT EDIT. */}}"
        echo "{{/* Source: grafana-operator chart ${CHART_VERSION} (operator ${APP_VERSION}) */}}"
        echo "{{/*         files/crds/$(basename "$src") */}}"
        # Inject the shared annotations under the CRD's own metadata.annotations.
        # The only two-space-indented `annotations:` key is metadata's -- schema
        # properties sit far deeper -- and the guard stops after the first hit.
        awk '
            { print }
            !injected && /^  annotations:$/ {
                print "{{- with .Values.crds.annotations }}"
                print "{{- toYaml . | nindent 4 }}"
                print "{{- end }}"
                injected = 1
            }
            END {
                if (!injected) {
                    print "missing metadata.annotations block" > "/dev/stderr"
                    exit 1
                }
            }
        ' "$src"
        echo "{{- end -}}"
    } >"$out_file"
done

# Guard against upstream adding or removing a CRD without the hand-maintained
# toggles in values.yaml keeping up -- a missing key renders as a nil deref.
_info "Checking values.yaml toggles against the generated set"
declare -a missing=()
for plural in "${plurals[@]}"; do
    if [ "$(yq e ".crds.${plural}.enabled // \"null\"" "$OUT_CHART_DIR/values.yaml")" = "null" ]; then
        missing+=("$plural")
    fi
done
if [ "${#missing[@]}" -gt 0 ]; then
    _error "$OUT_CHART_DIR/values.yaml is missing crds.<name>.enabled for:"
    printf '  %s\n' "${missing[@]}" >&2
    exit 1
fi

declare -a extra=()
while read -r key; do
    [ "$key" = "annotations" ] && continue
    # shellcheck disable=SC2076 # literal match is intended
    if [[ ! " ${plurals[*]} " =~ " ${key} " ]]; then
        extra+=("$key")
    fi
done < <(yq e '.crds | keys | .[]' "$OUT_CHART_DIR/values.yaml")
if [ "${#extra[@]}" -gt 0 ]; then
    _error "$OUT_CHART_DIR/values.yaml has toggles for CRDs upstream no longer ships:"
    printf '  %s\n' "${extra[@]}" >&2
    exit 1
fi

# Keep appVersion tracking the operator the CRDs were lifted from. The chart
# `version` stays 0.0.0 -- it is a local subchart, pinned by path, never
# resolved from a repository.
yq e -i ".appVersion = \"$APP_VERSION\"" "$OUT_CHART_DIR/Chart.yaml"

_info "Done. Wrote ${#plurals[@]} CRD template(s) to $OUT_CHART_DIR/templates"
